def build_interpretation_prompt(contract: PredictionInputContract) -> str:
    """Constructs the user prompt containing the verified prediction snapshot."""
    contract_json = contract.model_dump_json(indent=2)
    return f"""Please interpret the following validated Nifty 50 ML prediction contract and provide your structured risk analysis:

```json
{contract_json}
```

Instructions:
- Provide rigorous institutional interpretation adhering strictly to the required JSON schema.
- Distinguish the ML forecast from your interpretation.
- Do not fabricate option Greeks, premiums, or unverified events.
- Ensure decision_status is "ANALYSIS_ONLY".
"""


def extract_and_validate_analysis(
    raw_content: str,
    provider: str,
    model: str,
    latency_ms: float
) -> AIAnalysisOutput:
    """
    Extracts JSON from the model response, validates against AIAnalysisOutput schema,
    and returns a guaranteed structured object.
    """
    clean_text = raw_content.strip()

    # Strip markdown code fence if present
    json_match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", clean_text)
    if json_match:
        clean_text = json_match.group(1).strip()
    elif clean_text.startswith("{") and clean_text.endswith("}"):
        clean_text = clean_text
    else:
        # Fallback: find first { and last }
        start = clean_text.find("{")
        end = clean_text.rfind("}")
        if start != -1 and end != -1 and end > start:
            clean_text = clean_text[start:end + 1]

    try:
        parsed = json.loads(clean_text)
    except json.JSONDecodeError as exc:
        logger.error(f"Failed to parse JSON from {provider}/{model}: {exc}. Raw content preview: {raw_content[:200]}")
        raise ValueError(f"Model {model} did not return valid JSON: {str(exc)}")

    if not isinstance(parsed, dict):
        raise ValueError(f"Model {model} returned JSON that is not an object/dict")

    # Inject metadata
    parsed["provider"] = provider
    parsed["model"] = model
    parsed["latency_ms"] = latency_ms
    parsed["decision_status"] = "ANALYSIS_ONLY"
    parsed["status"] = "OK"

    # Enforce Pydantic validation
    try:
        validated = AIAnalysisOutput.model_validate(parsed)
        return validated
    except Exception as exc:
        logger.error(f"Schema validation failure for {provider}/{model}: {exc}")
        raise ValueError(f"Model {model} output failed schema validation: {str(exc)}")
